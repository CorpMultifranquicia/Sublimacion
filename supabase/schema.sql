create extension if not exists "pgcrypto";

-- ---------- Tablas ----------

create table if not exists insumos (
    id uuid primary key default gen_random_uuid(),
    nombre text not null,
    categoria text not null check (categoria in ('Consumible', 'Sustrato')),
    unidad_medida text not null,
    costo_unitario numeric(12,4) not null default 0,
    stock_actual numeric(12,2) not null default 0,
    stock_minimo numeric(12,2) not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists productos_finales (
    id uuid primary key default gen_random_uuid(),
    nombre text not null,
    categoria text not null,
    precio_venta numeric(12,2) not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists recetas_detalle (
    id uuid primary key default gen_random_uuid(),
    producto_id uuid not null references productos_finales(id) on delete cascade,
    insumo_id uuid not null references insumos(id) on delete cascade,
    cantidad_usada numeric(12,4) not null,
    porcentaje_merma numeric(5,2) not null default 0
);

create table if not exists clientes (
    id uuid primary key default gen_random_uuid(),
    nombre text not null,
    telefono text,
    email text,
    fecha_especial date,
    tipo_fecha text,
    created_at timestamptz not null default now()
);

create table if not exists ventas (
    id uuid primary key default gen_random_uuid(),
    folio integer generated by default as identity,
    cliente_id uuid references clientes(id) on delete set null,
    fecha date not null default current_date,
    estado_produccion text not null default 'Por Diseñar'
        check (estado_produccion in ('Por Diseñar', 'Imprimiendo', 'Listo/Entregado')),
    created_at timestamptz not null default now()
);

create table if not exists ventas_detalle (
    id uuid primary key default gen_random_uuid(),
    venta_id uuid not null references ventas(id) on delete cascade,
    producto_id uuid references productos_finales(id) on delete set null,
    cantidad numeric(12,2) not null,
    precio_unitario numeric(12,2) not null
);

create table if not exists compras (
    id uuid primary key default gen_random_uuid(),
    folio integer generated by default as identity,
    proveedor text not null,
    fecha date not null default current_date,
    created_at timestamptz not null default now()
);

create table if not exists compras_detalle (
    id uuid primary key default gen_random_uuid(),
    compra_id uuid not null references compras(id) on delete cascade,
    insumo_id uuid references insumos(id) on delete set null,
    cantidad numeric(12,2) not null,
    costo_unitario numeric(12,4) not null
);

-- ---------- Row Level Security ----------
-- Los 2 administradores acceden con su cuenta de Supabase Auth (email/password).
-- Cualquier usuario autenticado tiene acceso total (no hay roles complejos).

alter table insumos enable row level security;
alter table productos_finales enable row level security;
alter table recetas_detalle enable row level security;
alter table clientes enable row level security;
alter table ventas enable row level security;
alter table ventas_detalle enable row level security;
alter table compras enable row level security;
alter table compras_detalle enable row level security;

do $$
declare
    t text;
begin
    for t in select unnest(array[
        'insumos', 'productos_finales', 'recetas_detalle', 'clientes',
        'ventas', 'ventas_detalle', 'compras', 'compras_detalle'
    ])
    loop
        execute format(
            'create policy "authenticated_full_access" on %I for all using (auth.role() = ''authenticated'') with check (auth.role() = ''authenticated'')',
            t
        );
    end loop;
end $$;

-- ---------- Funciones de negocio (transaccionales) ----------

-- Registra una venta y descuenta stock de insumos según la receta de cada producto vendido.
-- p_detalle: jsonb array de {"producto_id": uuid, "cantidad": number, "precio_unitario": number}
create or replace function registrar_venta(
    p_cliente_id uuid,
    p_fecha date,
    p_estado text,
    p_detalle jsonb
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
    v_venta_id uuid;
    v_item jsonb;
    v_receta record;
begin
    insert into ventas (cliente_id, fecha, estado_produccion)
    values (p_cliente_id, p_fecha, coalesce(p_estado, 'Por Diseñar'))
    returning id into v_venta_id;

    for v_item in select * from jsonb_array_elements(p_detalle)
    loop
        insert into ventas_detalle (venta_id, producto_id, cantidad, precio_unitario)
        values (
            v_venta_id,
            (v_item->>'producto_id')::uuid,
            (v_item->>'cantidad')::numeric,
            (v_item->>'precio_unitario')::numeric
        );

        for v_receta in
            select insumo_id, cantidad_usada, porcentaje_merma
            from recetas_detalle
            where producto_id = (v_item->>'producto_id')::uuid
        loop
            update insumos
            set stock_actual = stock_actual - (
                v_receta.cantidad_usada * (1 + v_receta.porcentaje_merma / 100) * (v_item->>'cantidad')::numeric
            )
            where id = v_receta.insumo_id;
        end loop;
    end loop;

    return v_venta_id;
end;
$$;

-- Registra una compra, aumenta stock y recalcula el costo unitario promedio ponderado.
-- p_items: jsonb array de {"insumo_id": uuid, "cantidad": number, "costo_unitario": number}
create or replace function registrar_compra(
    p_proveedor text,
    p_fecha date,
    p_items jsonb
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
    v_compra_id uuid;
    v_item jsonb;
    v_insumo record;
    v_valor_actual numeric;
    v_valor_nuevo numeric;
    v_stock_total numeric;
begin
    insert into compras (proveedor, fecha) values (p_proveedor, p_fecha)
    returning id into v_compra_id;

    for v_item in select * from jsonb_array_elements(p_items)
    loop
        insert into compras_detalle (compra_id, insumo_id, cantidad, costo_unitario)
        values (
            v_compra_id,
            (v_item->>'insumo_id')::uuid,
            (v_item->>'cantidad')::numeric,
            (v_item->>'costo_unitario')::numeric
        );

        select * into v_insumo from insumos where id = (v_item->>'insumo_id')::uuid for update;
        if found then
            v_valor_actual := v_insumo.costo_unitario * v_insumo.stock_actual;
            v_valor_nuevo := (v_item->>'costo_unitario')::numeric * (v_item->>'cantidad')::numeric;
            v_stock_total := v_insumo.stock_actual + (v_item->>'cantidad')::numeric;

            update insumos
            set costo_unitario = case when v_stock_total > 0 then (v_valor_actual + v_valor_nuevo) / v_stock_total else v_insumo.costo_unitario end,
                stock_actual = v_stock_total
            where id = v_insumo.id;
        end if;
    end loop;

    return v_compra_id;
end;
$$;

grant execute on function registrar_venta(uuid, date, text, jsonb) to authenticated;
grant execute on function registrar_compra(text, date, jsonb) to authenticated;
